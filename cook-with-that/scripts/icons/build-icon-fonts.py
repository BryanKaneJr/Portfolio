"""Build the two small icon fonts the app bundles, from the Material Symbols fonts (Apache 2.0) in node_modules.

Reads the Material names used in src/theme/icons.ts, subsets the outlined and filled Material Symbols fonts to just
those glyphs (a few KB each), and writes src/theme/iconGlyphs.ts with each name's character.

Run from the app folder after changing src/theme/icons.ts:  python3 scripts/icons/build-icon-fonts.py
Needs fonttools (pip install fonttools).
"""
import json
import re
import subprocess

SRC = 'node_modules/@expo-google-fonts/material-symbols'
CODES = json.load(open('node_modules/expo-symbols/build/android/symbols.json'))

text = open('src/theme/icons.ts').read()
outlined = set(re.findall(r"md: '([a-z_]+)'(?!, filled)", text)) | set(re.findall(r":\s*'([a-z_]+)',?\n", text.split('DISH_ICONS')[1]))
filled = set(re.findall(r"md: '([a-z_]+)', filled: true", text))
outlined |= set(re.findall(r"DISH_ICON_FALLBACK = '([a-z_]+)'", text))
missing = sorted(n for n in outlined | filled if n not in CODES)
assert not missing, f'unknown Material Symbols: {missing}'


def subset(font, names, out):
    cps = ','.join('U+%04X' % CODES[n] for n in sorted(names))
    subprocess.run(['pyftsubset', f'{SRC}/{font}', f'--unicodes={cps}', '--layout-features=', '--no-hinting',
                    f'--output-file={out}'], check=True)


subset('400Regular/MaterialSymbols_400Regular.ttf', outlined, 'assets/fonts/AppIcons.ttf')
subset('400Regular_Filled/MaterialSymbols_400Regular_Filled.ttf', filled, 'assets/fonts/AppIconsFilled.ttf')

with open('src/theme/iconGlyphs.ts', 'w') as f:
    f.write('// Generated by scripts/icons/build-icon-fonts.py. Do not edit.\n')
    f.write('export const GLYPHS: Record<string, string> = {\n')
    for n in sorted(outlined | filled):
        f.write(f"  {n}: '\\u{{{CODES[n]:x}}}',\n")
    f.write('};\n')
print(f'{len(outlined)} outlined, {len(filled)} filled glyphs')
