/**
 * Copies the game's emblems from game-icons.net (https://github.com/game-icons/icons, CC BY 3.0: credit each
 * artist) into src/ui/components/gameIcons.ts as plain path data, so the app draws them with react-native-svg and
 * stays offline. The repository is fetched once, without file contents, into scripts/data/game-icons
 * (git-ignored); only the icons listed here are checked out.  Run:  npm run icons:build
 *
 * To add an icon: browse https://game-icons.net, add `key: 'artist/name'` below, run the script, and use the key.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(__dirname, '..');
const REPO = path.join(ROOT, 'scripts/data/game-icons');
const OUT = path.join(ROOT, 'src/ui/components/gameIcons.ts');

/** Our name → the artist's folder and the icon's name in the repository. */
const PICKS: Record<string, string> = {
  // Resources in the top bar.
  gold: 'delapouite/coins',
  manpower: 'delapouite/closed-barbute',
  stability: 'lorc/scales',
  prestige: 'lorc/laurel-crown',
  threat: 'lorc/mailed-fist',
  book: 'lorc/open-book',
  // The realm, war and the world.
  crown: 'lorc/crown',
  swords: 'lorc/crossed-swords',
  ship: 'lorc/galleon',
  castle: 'delapouite/castle',
  siege: 'delapouite/trebuchet',
  cannon: 'lorc/cannon',
  flag: 'lorc/flying-flag',
  target: 'lorc/archery-target',
  scroll: 'lorc/scroll-unfurled',
  treaty: 'delapouite/shaking-hands',
  church: 'delapouite/church',
  plague: 'delapouite/plague-doctor-profile',
  harvest: 'lorc/wheat',
  coins: 'delapouite/two-coins',
  rebels: 'delapouite/pitchfork',
  marriage: 'lorc/linked-rings',
  death: 'lorc/tombstone',
  horse: 'delapouite/horse-head',
  // Units on the map, and the fire behind an enemy's arms.
  pikeman: 'delapouite/pikeman',
  fire: 'lorc/celebration-fire',
};

const git = (...args: string[]) => execFileSync('git', args, { cwd: REPO, stdio: ['ignore', 'pipe', 'inherit'] }).toString();

if (!fs.existsSync(path.join(REPO, '.git'))) {
  fs.mkdirSync(path.dirname(REPO), { recursive: true });
  execFileSync('git', ['clone', '--quiet', '--filter=blob:none', '--no-checkout', '--depth', '1', 'https://github.com/game-icons/icons', REPO], { stdio: 'inherit' });
}
const files = Object.values(PICKS).map(p => `${p}.svg`);
git('checkout', 'HEAD', '--', ...files);

const NAME = (artist: string) =>
  ({ lorc: 'Lorc', delapouite: 'Delapouite', 'carl-olsen': 'Carl Olsen', sbed: 'Sbed', skoll: 'Skoll', 'caro-asercion': 'Caro Asercion' })[artist] ?? artist;

const out: string[] = [];
const artists = new Set<string>();
for (const [key, pick] of Object.entries(PICKS)) {
  const svg = fs.readFileSync(path.join(REPO, `${pick}.svg`), 'utf8');
  if (!/viewBox="0 0 512 512"/.test(svg) || /transform=/.test(svg)) throw new Error(`${pick}: expected a plain 512 × 512 icon`);
  // Every icon is a black square with the emblem in white on it: keep the emblem.
  const d = [...svg.matchAll(/<path[^>]*?\sd="([^"]+)"/g)].map(m => m[1]).filter(x => x.trim() !== 'M0 0h512v512H0z');
  if (!d.length) throw new Error(`${pick}: no emblem found`);
  const artist = pick.split('/')[0];
  artists.add(NAME(artist));
  out.push(`  ${/^[a-z]+$/.test(key) ? key : `'${key}'`}: { d: '${d.join(' ')}', by: '${NAME(artist)}', src: '${pick}' },`);
}

fs.writeFileSync(
  OUT,
  `/**
 * Emblems from game-icons.net (CC BY 3.0) by ${[...artists].sort().join(' and ')}: a 512 × 512 path each.
 * Generated by scripts/build-icons.ts (npm run icons:build): do not edit by hand. Credited in Settings (About) and the README.
 */
export const GLYPH_CREDIT = 'Icons by ${[...artists].sort().join(' and ')} from game-icons.net (CC BY 3.0).';

export const GLYPHS = {
${out.join('\n')}
} as const;

export type GlyphName = keyof typeof GLYPHS;
`,
);
console.log(`${Object.keys(PICKS).length} icons by ${[...artists].join(', ')} → ${path.relative(ROOT, OUT)}`);
