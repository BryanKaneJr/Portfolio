/**
 * Makes the owner's troop drawings (art/troops) ready for the map: each is cut to what is drawn and made smaller
 * (area-averaged, in premultiplied colour), written to assets/units/<name>.png, and listed with its size in
 * src/ui/map/troopArt.ts, which MapView's army tokens draw from.
 *
 *   npx tsx scripts/build-troops.ts        (npm run troops:build)
 */
import fs from 'node:fs';
import path from 'node:path';
import { PNG } from 'pngjs';

const ROOT = path.resolve(__dirname, '..');
const ART_DIR = path.join(ROOT, 'art/troops');
const OUT_DIR = path.join(ROOT, 'assets/units');
const OUT_TS = path.join(ROOT, 'src/ui/map/troopArt.ts');
/** Pixels, the figure's height: enough for the tallest token (about 55 points at the closest zoom) on a 3x screen. */
const HEIGHT = 192;

const ART = [
  { name: 'soldier-a', what: 'a lone halberdier' },
  { name: 'soldier-b', what: 'a lone halberdier, slashed sleeves' },
  { name: 'squad-4', what: 'four pikemen' },
  { name: 'squad-5', what: 'five men, pikes and a halberd' },
] as const;

function bake(name: string): { w: number; h: number } {
  const src = PNG.sync.read(fs.readFileSync(path.join(ART_DIR, `${name}.png`)));
  // What is drawn: the bounds of everything not transparent. The bottom is where the figure stands.
  let x0 = src.width, y0 = src.height, x1 = 0, y1 = 0;
  for (let y = 0; y < src.height; y++)
    for (let x = 0; x < src.width; x++)
      if (src.data[(y * src.width + x) * 4 + 3] > 8) {
        x0 = Math.min(x0, x);
        y0 = Math.min(y0, y);
        x1 = Math.max(x1, x + 1);
        y1 = Math.max(y1, y + 1);
      }
  const cw = x1 - x0;
  const ch = y1 - y0;
  const oh = Math.min(HEIGHT, ch);
  const ow = Math.round((cw * oh) / ch);
  const acc = new Float64Array(ow * oh * 4); // r, g, b (premultiplied), alpha; each output pixel's weights sum to 1
  for (let y = 0; y < ch; y++) {
    const oy0 = (y * oh) / ch;
    const oy1 = ((y + 1) * oh) / ch;
    for (let x = 0; x < cw; x++) {
      const ox0 = (x * ow) / cw;
      const ox1 = ((x + 1) * ow) / cw;
      const i = ((y0 + y) * src.width + x0 + x) * 4;
      const a = src.data[i + 3] / 255;
      if (a === 0) continue;
      for (let oy = Math.floor(oy0); oy < Math.min(oh, Math.ceil(oy1)); oy++) {
        const wy = Math.min(oy1, oy + 1) - Math.max(oy0, oy);
        for (let ox = Math.floor(ox0); ox < Math.min(ow, Math.ceil(ox1)); ox++) {
          const wgt = wy * (Math.min(ox1, ox + 1) - Math.max(ox0, ox));
          if (wgt <= 0) continue;
          const o = (oy * ow + ox) * 4;
          acc[o] += src.data[i] * a * wgt;
          acc[o + 1] += src.data[i + 1] * a * wgt;
          acc[o + 2] += src.data[i + 2] * a * wgt;
          acc[o + 3] += a * wgt;
        }
      }
    }
  }
  const out = new PNG({ width: ow, height: oh });
  for (let p = 0; p < ow * oh; p++) {
    const a = acc[p * 4 + 3];
    out.data[p * 4 + 3] = Math.round(Math.min(1, a) * 255);
    for (let c = 0; c < 3; c++) out.data[p * 4 + c] = a > 0 ? Math.round(Math.min(255, acc[p * 4 + c] / acc[p * 4 + 3])) : 0;
  }
  fs.writeFileSync(path.join(OUT_DIR, `${name}.png`), PNG.sync.write(out, { colorType: 6 }));
  return { w: ow, h: oh };
}

const sizes = ART.map(a => bake(a.name));
fs.writeFileSync(
  OUT_TS,
  `// Generated by scripts/build-troops.ts from art/troops (the owner's drawings). Do not edit; run npm run troops:build.
/** The army figures: each picture's size in pixels; the figure stands on its bottom edge. */
export const TROOP_ART = {
${ART.map((a, i) => `  '${a.name}': { src: require('../../../assets/units/${a.name}.png'), w: ${sizes[i].w}, h: ${sizes[i].h} }, // ${a.what}`).join('\n')}
} as const;
export type TroopArt = keyof typeof TROOP_ART;
`,
);
